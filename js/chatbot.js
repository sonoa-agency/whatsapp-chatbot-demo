/**
 * يبحث عن رد مناسب لرسالة المستخدم.
 * @param {string} userText نص رسالة المستخدم
 * @returns {{intent: string, reply: string}}
 */
function findReply(userText) {
  var normalized = userText.trim();

  for (var i = 0; i < INTENTS.length; i++) {
    var intent = INTENTS[i];
    for (var k = 0; k < intent.keywords.length; k++) {
      if (normalized.indexOf(intent.keywords[k]) !== -1) {
        return { intent: intent.name, reply: intent.reply };
      }
    }
  }
  return { intent: 'fallback', reply: FALLBACK_REPLY };
}

